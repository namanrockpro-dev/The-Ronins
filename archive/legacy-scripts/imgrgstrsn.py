def extract_physical_geometry(H):
    """
    Decomposes 3x3 Homography Matrix H into physical satellite parameters:
    - Relative Rotation Angle (theta in degrees)
    - Relative Zoom Scale Factor (S)
    - Physical Translation Shift (Delta X, Delta Y in pixels)
    """
    if H is None:
        return 0.0, 1.0, 0.0, 0.0

    h00, h10 = H[0, 0], H[1, 0]
    h01, h11 = H[0, 1], H[1, 1]

    scale_x = math.sqrt(h00**2 + h10**2)
    scale_y = math.sqrt(h01**2 + h11**2)
    avg_scale = (scale_x + scale_y) / 2.0

    rotation_rad = math.atan2(h10, h00)
    rotation_deg = math.degrees(rotation_rad)

    shift_x = H[0, 2]
    shift_y = H[1, 2]

    return rotation_deg, avg_scale, shift_x, shift_y

def run_sift_baseline_benchmark(imgA, imgB):
    """
    Runs classical SIFT + RANSAC baseline to prove to judges that
    traditional methods fail under harsh space payload conditions.
    """
    sift = cv2.SIFT_create(nfeatures=2000)
    kpA, desA = sift.detectAndCompute(imgA, None)
    kpB, desB = sift.detectAndCompute(imgB, None)

    if desA is None or desB is None or len(kpA) < 4 or len(kpB) < 4:
        return 0, 0

    bf = cv2.BFMatcher()
    matches = bf.knnMatch(desA, desB, k=2)

    good_matches = []
    for pair in matches:
        if len(pair) == 2:
            m, n = pair
            if m.distance < 0.75 * n.distance:
                good_matches.append(m)

    if len(good_matches) < 4:
        return len(good_matches), 0

    ptsA = np.float32([kpA[m.queryIdx].pt for m in good_matches]).reshape(-1, 1, 2)
    ptsB = np.float32([kpB[m.trainIdx].pt for m in good_matches]).reshape(-1, 1, 2)

    H, mask = cv2.findHomography(ptsA, ptsB, cv2.RANSAC, 5.0)
    sift_inliers = int(mask.sum()) if mask is not None else 0

    return len(good_matches), sift_inliers

def draw_clean_correspondence_lines(imgA, imgB, ptsA, ptsB, box, max_lines=60):
    """Visualizes clean, high-contrast match vectors restricted to ROI."""
    hA, wA = imgA.shape
    hB, wB = imgB.shape

    x, y, bw, bh = [int(v) for v in box]
    pad = 15
    x1, y1 = max(0, x - pad), max(0, y - pad)
    x2, y2 = min(wB, x + bw + pad), min(hB, y + bh + pad)
    cropB = imgB[y1:y2, x1:x2]

    dispA = cv2.resize(imgA, (cropB.shape[1], cropB.shape[0]), interpolation=cv2.INTER_AREA)

    scale_x = cropB.shape[1] / wA
    scale_y = cropB.shape[0] / hA

    ptsA_disp = ptsA.copy()
    ptsA_disp[:, 0] *= scale_x
    ptsA_disp[:, 1] *= scale_y

    ptsB_disp = ptsB.copy()
    ptsB_disp[:, 0] -= x1
    ptsB_disp[:, 1] -= y1

    hC, wC = cropB.shape
    canvas = np.zeros((hC, wC * 2), dtype=np.uint8)
    canvas[:, :wC] = dispA
    canvas[:, wC:] = cropB
    canvas_bgr = cv2.cvtColor(canvas, cv2.COLOR_GRAY2BGR)

    n_draw = min(len(ptsA_disp), max_lines)
    idx = np.linspace(0, len(ptsA_disp) - 1, n_draw, dtype=int) if len(ptsA_disp) > 0 else []

    for i in idx:
        p1 = (int(ptsA_disp[i, 0]), int(ptsA_disp[i, 1]))
        p2 = (int(ptsB_disp[i, 0] + wC), int(ptsB_disp[i, 1]))
        cv2.line(canvas_bgr, p1, p2, (0, 255, 80), 1, cv2.LINE_AA)
        cv2.circle(canvas_bgr, p1, 3, (0, 0, 255), -1)
        cv2.circle(canvas_bgr, p2, 3, (255, 200, 0), -1)

    return canvas_bgr

