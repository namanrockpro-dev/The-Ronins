# CELL 5 / MODULE 4 (ROI-CROPPED ENGINE): DENSE LOCAL MATCHING & SUB-PIXEL REFINER
# Crops Payload B around the Module 3 box so LoFTR matches ONLY the crater region!
# ==============================================================================
import os
import cv2
import numpy as np
import torch
import kornia
import matplotlib.pyplot as plt

def enforce_anms_grid_uniformity(ptsA, ptsB_local, roi_shape, grid_size=(5, 5), max_pts_per_cell=6):
    """
    Quad-Tree ANMS 5x5 Grid Allocator enforced strictly inside the cropped ROI box.
    Guarantees that points never float outside the ROI bounding box.
    """
    h_roi, w_roi = roi_shape
    cell_w = w_roi / grid_size[1]
    cell_h = h_roi / grid_size[0]

    cell_buckets = {}

    for i, (ptA, ptB) in enumerate(zip(ptsA, ptsB_local)):
        col = int(ptB[0] / (cell_w + 1e-5))
        row = int(ptB[1] / (cell_h + 1e-5))

        col = max(0, min(grid_size[1] - 1, col))
        row = max(0, min(grid_size[0] - 1, row))

        cell_key = (row, col)
        if cell_key not in cell_buckets:
            cell_buckets[cell_key] = []
        cell_buckets[cell_key].append(i)

    uniform_indices = []
    for cell_key, indices in cell_buckets.items():
        if len(indices) > max_pts_per_cell:
            selected = np.random.choice(indices, size=max_pts_per_cell, replace=False)
            uniform_indices.extend(selected)
        else:
            uniform_indices.extend(indices)

    grid_coverage_pct = (len(cell_buckets) / (grid_size[0] * grid_size[1])) * 100.0
    return np.array(uniform_indices), grid_coverage_pct

def run_loftr_dense_roi(imgA, roiB, device, target_size=640):
    """Runs LoFTR densely between Payload A and the cropped ROI of Payload B."""
    hA, wA = imgA.shape
    hB, wB = roiB.shape

    resA = cv2.resize(imgA, (target_size, target_size), interpolation=cv2.INTER_AREA)
    resB = cv2.resize(roiB, (target_size, target_size), interpolation=cv2.INTER_AREA)

    tA = torch.from_numpy(resA).float()[None, None] / 255.0
    tB = torch.from_numpy(resB).float()[None, None] / 255.0

    matcher = kornia.feature.LoFTR(pretrained='outdoor').to(device).eval()

    with torch.inference_mode():
        out = matcher({"image0": tA.to(device), "image1": tB.to(device)})

    mask = out["confidence"] > 0.20
    kA = out["keypoints0"][mask].cpu().numpy()
    kB = out["keypoints1"][mask].cpu().numpy()

    if len(kA) < 4:
        return np.zeros((0, 2)), np.zeros((0, 2))

    # Scale keypoints back to native crop sizes
    kA[:, 0] *= (wA / target_size)
    kA[:, 1] *= (hA / target_size)
    kB[:, 0] *= (wB / target_size)
    kB[:, 1] *= (hB / target_size)

    return kA, kB

def lucas_kanade_roi_refine(rawA, raw_roiB, ptsA, ptsB_local, H_coarse):
    """Lucas-Kanade Optical Flow refinement on raw uncompressed ROI pixels."""
    hB, wB = raw_roiB.shape
    rawA_warped = cv2.warpPerspective(rawA, H_coarse, (wB, hB))
    ptsA_warped = cv2.perspectiveTransform(ptsA.reshape(-1, 1, 2), H_coarse).reshape(-1, 2)

    lk_params = dict(
        winSize=(21, 21),
        maxLevel=3,
        criteria=(cv2.TERM_CRITERIA_EPS | cv2.TERM_CRITERIA_COUNT, 30, 0.01)
    )

    p0 = ptsA_warped.astype(np.float32).reshape(-1, 1, 2)
    p1, status, err = cv2.calcOpticalFlowPyrLK(rawA_warped, raw_roiB, p0, None, **lk_params)

    refined_ptsB = []
    for i in range(len(p0)):
        if status[i] == 1 and err[i] < 8.0:
            refined_ptsB.append(p1[i].ravel())
        else:
            refined_ptsB.append(ptsB_local[i])

    return np.array(refined_ptsB)

def run_module_4_roi_engine(rawA, rawB, procA, procB, loc_data):
    print("=" * 65)
    print(" 🎯 MODULE 4: ROI-CROPPED DENSE MATCHING & SUB-PIXEL REFINER")
    print("=" * 65)

    if loc_data is None:
        print("❌ MODULE 4 FAILED: Location data from Module 3 is missing.")
        return None

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    box = loc_data["box"] # (x_min, y_min, box_w, box_h)
    M_affine = loc_data["M_affine"]

    # 1. CROP PAYLOAD B STRICTLY AROUND THE DISCOVERED ROI (with 10% safety margin)
    x, y, bw, bh = box
    pad_x = int(bw * 0.10)
    pad_y = int(bh * 0.10)

    hB_full, wB_full = rawB.shape
    x1, y1 = max(0, x - pad_x), max(0, y - pad_y)
    x2, y2 = min(wB_full, x + bw + pad_x), min(hB_full, y + bh + pad_y)

    print(f"✂️ Cropping Payload B around Crater ROI: [{x1}:{x2}, {y1}:{y2}] ({x2-x1}x{y2-y1} px)")
    procB_roi = procB[y1:y2, x1:x2]
    rawB_roi = rawB[y1:y2, x1:x2]

    # Warp procA using coarse matrix M so it matches procB_roi orientation
    procA_warped = cv2.warpAffine(procA, M_affine, (wB_full, hB_full))[y1:y2, x1:x2]
    rawA_warped = cv2.warpAffine(rawA, M_affine, (wB_full, hB_full))[y1:y2, x1:x2]

    # 2. RUN LoFTR DENSE MATCHING STRICTLY INSIDE THE ROI
    print(" Running Deep LoFTR Matcher on ROI crop...")
    kA_roi, kB_roi = run_loftr_dense_roi(procA_warped, procB_roi, device)

    print(f"   Raw Dense Matches Found Inside Crater ROI: {len(kA_roi)} points")

    if len(kA_roi) < 4:
        print("❌ Dense LoFTR matching failed inside ROI crop.")
        return None

    # 3. ENFORCE ANMS 5x5 GRID UNIFORMITY STRICTLY INSIDE THE ROI
    uniform_idx, grid_cov = enforce_anms_grid_uniformity(kA_roi, kB_roi, roi_shape=procB_roi.shape)
    unif_kA = kA_roi[uniform_idx]
    unif_kB = kB_roi[uniform_idx]

    print(f"   ANMS Filtered Uniform Inliers            : {len(unif_kA)} points")
    print(f"   5x5 Grid Spatial Coverage                : {grid_cov:.1f}% occupied")

    # 4. RUN LUCAS-KANADE OPTICAL FLOW SUB-PIXEL REFINEMENT ON UNCOMPRESSED ROI PIXELS
    H_roi_coarse, _ = cv2.findHomography(unif_kA, unif_kB, cv2.USAC_MAGSAC, 4.0)
    subpixel_kB = lucas_kanade_roi_refine(rawA_warped, rawB_roi, unif_kA, unif_kB, H_roi_coarse)

    # 5. COMPUTE NATIVE HOMOGRAPHY & RMSE INSIDE ROI
    H_roi_native, inlier_mask = cv2.findHomography(unif_kA, subpixel_kB, cv2.USAC_MAGSAC, 2.5)

    if H_roi_native is None:
        print("❌ MAGSAC Homography calculation failed.")
        return None

    inliers_mask = inlier_mask.flatten().astype(bool)
    final_kA = unif_kA[inliers_mask]
    final_kB_local = subpixel_kB[inliers_mask]

    # Calculate Native Sub-Pixel RMSE inside ROI
    ptsA_trans = cv2.perspectiveTransform(final_kA.reshape(-1, 1, 2), H_roi_native).reshape(-1, 2)
    native_rmse = float(np.sqrt(np.mean(np.sum((ptsA_trans - final_kB_local)**2, axis=1))))

    # 6. MAP LOCAL ROI POINTS BACK TO FULL PAYLOAD B GLOBAL CANVAS
    final_kB_global = final_kB_local.copy()
    final_kB_global[:, 0] += x1
    final_kB_global[:, 1] += y1

    # Un-warp final_kA back to original un-rotated Payload A space
    M_inv = cv2.invertAffineTransform(M_affine)
