def natural_photometric_enhancer(img):
    """
    Cleans sensor noise and brightens dark crater shadows gently.
    Keeps natural surface texture crisp without introducing grain or noise maps.
    """
    # 1. Bilateral Denoising: Kills background noise, preserves crater rim edges
    denoised = cv2.bilateralFilter(img, d=7, sigmaColor=35, sigmaSpace=35)

    # 2. Percentile Clipping: Normalizes brightness range [2%, 98%]
    p2, p98 = np.percentile(denoised, (2, 98))
    if p98 > p2:
        norm = np.clip((denoised - p2) / (p98 - p2) * 255.0, 0, 255).astype(np.uint8)
    else:
        norm = denoised

    # 3. Gentle CLAHE: Brightens shadow interiors without blowing out highlights
    clahe = cv2.createCLAHE(clipLimit=1.8, tileGridSize=(8, 8))
    enhanced = clahe.apply(norm)

    return enhanced

